// Generates supabase/functions/afqe-parse/core.js (an ES module) from index.html, so the market scanner
// parses and scores exactly like the page. The edge functions import core.js from this repo pinned to a commit SHA.
// Usage (repo root): node tools/build_edge.js   → commit + push → update the pinned SHA in the edge functions → redeploy.
const fs = require('fs');
const html = fs.readFileSync('index.html', 'utf8');
const region = (a, b) => { const i = html.indexOf(a), k = html.indexOf(b); if (i < 0 || k < 0) throw new Error('region not found: ' + a); return html.slice(i, k + b.length); };
const grab = (re, what) => { const m = html.match(re); if (!m) throw new Error('not found: ' + what); return m[0]; };
const core = region('/*CORE-START*/', '/*CORE-END*/');
const scoring = region('/*SCORE-START*/', '/*SCORE-END*/');
const out = `// GENERATED by tools/build_edge.js from index.html — do not edit by hand.
// Needs a global DOMParser (the edge function sets one from linkedom before importing).
const fin = (x) => typeof x === "number" && isFinite(x);
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));
const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const sdev = (a) => { if (a.length < 2) return NaN; const m = mean(a); return Math.sqrt(a.reduce((s, x) => s + (x - m) * (x - m), 0) / (a.length - 1)); };
const num = (x) => { if (x == null) return NaN; const s = String(x).replace(/[,₹%\\s]/g, ""); return s === "" ? NaN : parseFloat(s); };
${grab(/const f1=x=>[^\n]*/, 'format helpers')}
${grab(/function erf\(x\)[^\n]*/, 'erf')}
${grab(/const Phi=[^\n]*/, 'Phi')}
${grab(/function lin\(x,x0,x1,pts,miss,label\)[^\n]*/, 'lin')}
${grab(/const SECT=\{[\s\S]*?\};/, 'SECT')}
${grab(/const COLS=\[[\s\S]*?\n\];/, 'COLS')}
${grab(/const DEF=\{[\s\S]*?\};/, 'DEF')}
let P = Object.assign({}, DEF);
const S = { over: {}, fund: [], scanRaw: [], _capU: [], _capF: { fq: {}, n: 0 }, lab: null, baseRates: null, promiseHit: {} };
${core}
${scoring}
// History replay: score each past financial year as of 4 months after it closed (annual results public),
// using only data available then, and attach what happened next (returns, sales and EBIT growth).
const rd = (x, k = 3) => (fin(x) ? Math.round(x * 10 ** k) / 10 ** k : null);
function panelRows(j, sym, st) {
  const out = [];
  for (let k = 1; k <= 9; k++) {
    let o;
    try { o = fromScreener(j, sym, st, k).o; } catch (e) { if (/not enough history/.test(String(e && e.message))) break; continue; }
    if (!fin(o.mcap_cr) || !fin(o.revenue_cr) || o.revenue_cr <= 0) continue;
    o.sector_type = st;
    let r; try { r = score(o); } catch (e) { continue; }
    const e = r.exp || {};
    out.push({ fy: o._fy, asof: o._asof, sec: st, rev: Math.round(o.revenue_cr), mcap: Math.round(o.mcap_cr),
      S: rd(r.S, 2), R: rd(r.R, 2), T: rd(r.T, 2), O: rd(r.O, 2), M: rd(r.M, 2), V: rd(r.V, 2), nmos: rd(r.nmos, 2), opt: rd(r.opt, 2),
      b: r.bucket, stage: r.stage, div: r.div, gates: r.gates.length, crowd: r.crowd,
      f: { roce: rd(o.roce, 1), dRoce: rd(r.dRoce, 1), ps: rd(r.ps, 2), evE: rd(r.evE, 1), conv: rd(r.conv, 2), ndE: rd(r.ndE, 2), dGM: rd(r.dGM, 1), dEM: rd(r.dEM, 1),
        iroce: rd(o.incr_roce_5y, 1), payoff: rd(o.capex_payoff, 2), capGap: fin(e.impliedCap) && fin(r.capYrs) ? Math.min(e.impliedCap, 80) - r.capYrs : null,
        implied: rd(e.implied), gest: rd(e.gest), pBeat: rd(e.pBeat), alloc: rd(r.alloc, 2), rg5: rd(o.rev_cagr_5y, 1), txP: rd(r.txP), txPh: r.txPh },
      fwd1: rd(o._fwd1), fwd3: rd(o._fwd3), fs3: rd(o._fs3), fs5: rd(o._fs5), fe3: rd(o._fe3) });
  }
  return out;
}
export { screenerHealth, fromScreener, parseExchange, sectorFromIndustry, parseRating, parseDocs, panelRows, COLS, SECT };
`;
fs.mkdirSync('supabase/functions/afqe-parse', { recursive: true });
fs.writeFileSync('supabase/functions/afqe-parse/core.js', out);
console.log('wrote supabase/functions/afqe-parse/core.js', out.length, 'bytes');
